#Requires -Version 5.1
[CmdletBinding()]
param([switch]$LegacyBlockout,[switch]$RefreshEvidence)
$ErrorActionPreference='Stop'
if(!$LegacyBlockout){
    & (Join-Path $PSScriptRoot 'test-c64-actors.ps1')
    & python (Join-Path $PSScriptRoot 'tools/audit_c64_world.py')
    if($LASTEXITCODE){throw 'Integrated C64 source world comparison failed'}
    & (Join-Path $PSScriptRoot 'test-source-contact.ps1')
    & python (Join-Path $PSScriptRoot 'tools/verify_source_sprite_copy.py')
    if($LASTEXITCODE){throw 'Source sprite copy comparison failed'}
    & (Join-Path $PSScriptRoot 'test-source-object.ps1')
    & (Join-Path $PSScriptRoot 'test-source-score.ps1')
    & (Join-Path $PSScriptRoot 'test-source-visibility.ps1')
    & (Join-Path $PSScriptRoot 'test-source-vic.ps1')
    & (Join-Path $PSScriptRoot 'test-vic-cache.ps1')
    & (Join-Path $PSScriptRoot 'test-source-audio.ps1')
    & (Join-Path $PSScriptRoot 'test-source-dma.ps1')
    & (Join-Path $PSScriptRoot 'test-scene-copy.ps1')
    & (Join-Path $PSScriptRoot 'test-source-paint.ps1')
    & (Join-Path $PSScriptRoot 'test-view-mask.ps1')
    & python (Join-Path $PSScriptRoot 'tools/verify_view_projection.py')
    if($LASTEXITCODE){throw 'Live projection evidence is stale or invalid'}
    if($RefreshEvidence){
        # Reports are regenerated by the controls above. Rebind only after
        # verifying current native source/build identities and all gates.
        # This cannot approve stale binaries or bypass a failed native run.
        & python (Join-Path $PSScriptRoot 'tools/verify_source_world_delivery.py') --record
        if($LASTEXITCODE){throw 'Cannot refresh delivery: native/source evidence is stale or failed'}
        & python (Join-Path $PSScriptRoot 'tools/verify_source_optimization.py') --record
        if($LASTEXITCODE){throw 'Cannot refresh measured optimization evidence'}
    }
    & python (Join-Path $PSScriptRoot 'tools/verify_source_world_delivery.py')
    if($LASTEXITCODE){throw 'Source-world delivery is stale or has failed scoped gates; run test-source-world.ps1 and record the delivery'}
    & python (Join-Path $PSScriptRoot 'tools/verify_source_optimization.py')
    if($LASTEXITCODE){throw 'Measured optimization evidence is stale or invalid'}
    Write-Output 'PASS scoped complete source chain/audio/DMA/scene controls; edition, raster phase, real-time budget and natural play remain open'
    return
}
throw 'LegacyBlockout comparisons are historical. Use test-parity.ps1 without LegacyBlockout; see docs/TEST_AUDIT_2026-10-25.md.'
