"""Select short transients from local AudioGen WAVs; build 4-bit companded SFX.

Run with the AudioGen Python (numpy/scipy/soundfile). Inputs are immutable.
Runtime decoding is one table lookup per sample, once at program startup.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parents[1]
RATE = 8000
LEVELS = np.array([-120, -82, -55, -36, -23, -13, -6, 0,
                    0, 6, 13, 23, 36, 55, 82, 120], dtype=np.int16)


def build():
    output = ROOT / 'assets/audio/combat-v1'
    output.mkdir(parents=True, exist_ok=True)
    parts, records, offset = [], [], 0
    for kind, milliseconds in [('punch', 100), ('kick', 150)]:
        for variant in range(2):
            source = output / f'{kind}_{variant}_source.wav'
            waveform, rate = sf.read(source, always_2d=True)
            waveform = waveform.mean(axis=1)
            # Find strongest 10ms energy window, retain 12ms of its attack.
            energy = np.convolve(waveform ** 2, np.ones(max(1, rate // 100)), 'valid')
            start = max(0, int(np.argmax(energy)) - int(rate * .012))
            chunk = waveform[start:start + int(rate * milliseconds / 1000)]
            chunk = resample_poly(chunk, RATE, rate)
            count = RATE * milliseconds // 1000
            chunk = np.pad(chunk[:count], (0, max(0, count - len(chunk))))
            chunk -= chunk.mean()
            chunk *= 112 / max(1e-9, np.max(np.abs(chunk)))
            fade = 32
            chunk[:fade] *= np.linspace(0, 1, fade)
            chunk[-fade:] *= np.linspace(1, 0, fade)
            codes = np.abs(chunk[:, None] - LEVELS[None, :]).argmin(axis=1).astype(np.uint8)
            decoded = LEVELS[codes].astype(np.int8)
            packed = (codes[::2] << 4) | codes[1::2]
            assert np.array_equal(LEVELS[np.column_stack((packed >> 4, packed & 15)).ravel()], decoded)
            preview = output / f'{kind}_{variant}.wav'
            if preview.exists():
                raise SystemExit(f'Refusing to replace selected audio: {preview}')
            sf.write(preview, decoded.astype(float) / 128, RATE, subtype='PCM_U8')
            parts.append(bytes(packed))
            records.append(dict(name=f'{kind}_{variant}', offset=offset, samples=count,
                                duration_ms=milliseconds, source_start_sample=start,
                                source_rate=rate, source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                                packed_sha256=hashlib.sha256(packed.tobytes()).hexdigest(),
                                peak=int(np.max(np.abs(decoded.astype(int)))),
                                rms=float(np.sqrt(np.mean(decoded.astype(float) ** 2)))))
            offset += count
    data = b''.join(parts)
    header = '/* Generated by tools/build_combat_audio.py; AudioGen sources, no C64 audio. */\n'
    header += f'#define BL_SFX_PCM_BYTES {offset}\n#define BL_SFX_CHIP_BYTES {offset + 4}\n'
    header += 'static const signed char bl_sfx_levels[16]={' + ','.join(map(str, LEVELS)) + '};\n'
    header += 'static const unsigned short bl_sfx_offsets[4]={' + ','.join(str(r['offset']) for r in records) + '};\n'
    header += 'static const unsigned short bl_sfx_lengths[4]={' + ','.join(str(r['samples']) for r in records) + '};\n'
    header += 'static const unsigned char bl_sfx_packed[]={\n'
    header += '\n'.join(','.join(str(v) for v in data[i:i+24]) + ',' for i in range(0, len(data), 24)) + '\n};\n'
    (ROOT / 'amiga/combat_audio_data.h').write_text(header, encoding='ascii')
    report = dict(generator='local AudioGen medium', rate=RATE, codec='4-bit logarithmic PCM, decoded to signed 8-bit for Paula',
                  packed_bytes=len(data), chip_bytes=offset + 4, variants=records,
                  runtime_pitch_periods=[422, 432, 443, 454, 465], original_audio_used=False)
    (output / 'manifest.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    build()
