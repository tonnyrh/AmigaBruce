"""Derived VIC occupancy for combat, from the real sprite writer/positions.

Each row stores24 doubled-X pixels on the existing48x21 canvas. Colours
are irrelevant to $D01E; opaque black remains occupied. This is separate
from the source's $5212 background/contact masks.
"""
import hashlib,json
from pathlib import Path
from build_c64_sprites import ROOT,SOURCE,SHA,ACTORS,source_frame

def main():
    source=SOURCE.read_bytes();assert hashlib.sha256(source).hexdigest()==SHA
    unique={};rows=[];indices=[];self_contact=[]
    for name,actor,offset in ACTORS:
        for facing in range(2):
            for pose in range(0,70,2):
                pixels,parts=source_frame(source,actor,pose,facing)
                mask=tuple(sum(1<<(23-x) for x in range(24)
                    if pixels[y*48+x*2] is not None) for y in range(21))
                assert all((pixels[y*48+x*2] is None)==(pixels[y*48+x*2+1] is None)
                    for y in range(21) for x in range(24))
                if mask not in unique:unique[mask]=len(rows);rows.append(mask)
                indices.append(unique[mask])
                occupied=[]
                for part in parts:
                    bits=bytes.fromhex(part['bits'])
                    occupied.append({(part['x_offset']+x*2,part['y_offset']+y)
                        for y in range(21) for x in range(24)
                        if bits[y*3+x//8]&(128>>(x&7))})
                self_contact.append(int(any(occupied[i]&occupied[j]
                    for i in range(len(occupied)) for j in range(i))))
    assert len(rows)<256
    path=ROOT/'core/c64_hit_data.h'
    path.write_text('/* Generated by build_c64_hit_masks.py; frozen source SHA256 '+SHA+' */\n'+
        'static const unsigned char hit_frame[210]={'+','.join(map(str,indices))+'};\n'+
        'static const unsigned char hit_self[210]={'+','.join(map(str,self_contact))+'};\n'+
        f'static const unsigned long hit_rows[{len(rows)}][21]={{\n'+
        ',\n'.join('{'+','.join(f'0x{x:06x}UL' for x in row)+'}' for row in rows)+'\n};\n',encoding='ascii')
    out=ROOT/'reference/analysis/ninja-wall-2026-10-26';out.mkdir(parents=True,exist_ok=True)
    def artifact(p):return dict(path=p.relative_to(ROOT).as_posix(),sha256=hashlib.sha256(p.read_bytes()).hexdigest())
    (out/'masks.json').write_text(json.dumps(dict(source_sha256=SHA,edition_verified=False,
        frame_count=210,unique_masks=len(rows),cpu_bytes=420+len(rows)*84,chip_bytes=0,
        generator=artifact(Path(__file__)),dependency=artifact(ROOT/'tools/build_c64_sprites.py'),
        output=artifact(path)),indent=2)+'\n',encoding='utf-8')
    print(f'VIC hit masks:210 frames,{len(rows)} unique,{420+len(rows)*84} CPU bytes;0 Chip bytes')
if __name__=='__main__':main()
