"""Convert a new local AudioGen kiai to mono Paula PCM and 4-bit IMA ADPCM.

The runtime decodes into the unused second screen buffer, so no extra Chip
allocation survives (or is needed during) startup. Existing audio is immutable.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parents[1]
RATE = 11025
PERIOD = 322  # PAL Paula: 3546895 / 322 = 11015.2 Hz.
STEPS = (7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,
         50,55,60,66,73,80,88,97,107,118,130,143,157,173,190,209,230,
         253,279,307,337,371,408,449,494,544,598,658,724,796,876,963,
         1060,1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,
         3327,3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,
         10442,11487,12635,13899,15289,16818,18500,20350,22385,24623,
         27086,29794,32767)
INDEX = (-1,-1,-1,-1,2,4,6,8)


def decode(codes):
    predictor = index = 0
    output = []
    for code in codes:
        step = STEPS[index]
        delta = step // 8
        if code & 4: delta += step
        if code & 2: delta += step // 2
        if code & 1: delta += step // 4
        predictor += -delta if code & 8 else delta
        predictor = min(32767, max(-32768, predictor))
        index = min(88, max(0, index + INDEX[code & 7]))
        output.append(predictor >> 8)
    return np.array(output, dtype=np.int8)


def encode(pcm):
    predictor = index = 0
    codes = []
    for sample in pcm:
        step = STEPS[index]
        difference = int(sample) - predictor
        code = 8 if difference < 0 else 0
        difference = abs(difference)
        delta = step // 8
        if difference >= step:
            code |= 4
            difference -= step
            delta += step
        if difference >= step // 2:
            code |= 2
            difference -= step // 2
            delta += step // 2
        if difference >= step // 4:
            code |= 1
            delta += step // 4
        predictor += -delta if code & 8 else delta
        predictor = min(32767, max(-32768, predictor))
        index = min(88, max(0, index + INDEX[code & 7]))
        codes.append(code)
    return codes


def build(source):
    output = ROOT / 'assets/audio/intro-v1'
    preview = output / 'kiai-paula.wav'
    header = ROOT / 'amiga/intro_audio_data.h'
    manifest_path = output / 'manifest.json'
    for path in (preview, header, manifest_path):
        if path.exists():
            raise SystemExit(f'Refusing to replace existing audio output: {path}')
    waveform, rate = sf.read(source, always_2d=True)
    waveform = waveform.mean(axis=1)
    chunk = resample_poly(waveform, RATE // math.gcd(RATE, rate), rate // math.gcd(RATE, rate))
    chunk -= chunk.mean()
    chunk *= .88 / max(1e-9, np.max(np.abs(chunk)))
    # Preserve the whole utterance; only soften the clip boundaries.
    attack, release = int(RATE * .008), int(RATE * .03)
    chunk[:attack] *= np.linspace(0, 1, attack)
    chunk[-release:] *= np.linspace(1, 0, release)
    chunk = np.pad(chunk, (0, len(chunk) & 1))
    assert 0 < len(chunk) <= 40956  # Existing 40960-byte back buffer plus silence.
    reference = np.rint(chunk * 32767).astype(np.int16)
    codes = encode(reference)
    decoded = decode(codes)
    packed = bytes((codes[i] << 4) | codes[i + 1] for i in range(0, len(codes), 2))
    sf.write(preview, decoded.astype(float) / 128, RATE, subtype='PCM_U8')
    text = '/* Generated by tools/build_intro_audio.py. New local AudioGen voice. */\n'
    text += f'#define BL_INTRO_PCM_BYTES {len(decoded)}\n#define BL_INTRO_PERIOD {PERIOD}\n'
    text += '#define BL_INTRO_TIMEOUT_FIELDS 200\n'
    text += 'static const unsigned short bl_intro_steps[89]={' + ','.join(map(str, STEPS)) + '};\n'
    text += 'static const signed char bl_intro_index[8]={' + ','.join(map(str, INDEX)) + '};\n'
    text += 'static const unsigned char bl_intro_packed[]={\n'
    text += '\n'.join(','.join(str(v) for v in packed[i:i+24]) + ',' for i in range(0, len(packed), 24)) + '\n};\n'
    header.write_text(text, encoding='ascii')
    noise = reference.astype(float) / 256 - decoded.astype(float)
    manifest = dict(generator='local AudioGen medium', source=source.relative_to(ROOT).as_posix(),
                    source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(), rate=RATE,
                    paula_period=PERIOD, actual_pal_rate=3546895 / PERIOD,
                    codec='4-bit IMA ADPCM, zero initial predictor/index, high nibble first',
                    samples=len(decoded), duration_seconds=len(decoded) / (3546895 / PERIOD),
                    packed_bytes=len(packed), decoded_bytes=len(decoded), extra_chip_bytes=0,
                    runtime_storage='second 40960-byte game framebuffer, reused before first game frame',
                    original_audio_used=False, speech_or_exact_syllables_certified=False,
                    manual_listening_accepted=False,
                    packed_sha256=hashlib.sha256(packed).hexdigest(),
                    decoded_sha256=hashlib.sha256(decoded.tobytes()).hexdigest(),
                    conversion_snr_db=10 * math.log10(np.mean((reference.astype(float)/256)**2) / np.mean(noise**2)))
    manifest_path.write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    args = argparse.ArgumentParser()
    args.add_argument('source', type=Path)
    build(args.parse_args().source.resolve())
